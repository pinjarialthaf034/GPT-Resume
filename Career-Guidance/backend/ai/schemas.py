class ResumeAnalysisAIResponse(BaseModel):
    """
    Pydantic schema for Gemini's resume feedback.
    guidance_score is a career guidance readiness score (0-100),
    NOT an employer hiring score.
    """
    guidance_score: int = Field(..., ge=0, le=100)
    strengths: List[str] = Field(default_factory=list)
    missing_skills: List[str] = Field(default_factory=list)
    formatting_feedback: List[str] = Field(default_factory=list)
    project_suggestions: List[str] = Field(default_factory=list)
    skill_alignment: str = Field(..., min_length=10)
    improvement_suggestions: List[str] = Field(default_factory=list)


